create table if not exists public.banca_usuarios (
    id bigint generated by default as identity primary key,
    username text not null unique,
    nome_exibicao text not null,
    senha_hash text not null,
    papel text not null default 'judge' check (papel in ('admin','judge')),
    ativo boolean not null default true,
    falhas_login integer not null default 0,
    bloqueado_ate timestamptz
);

create table if not exists public.banca_equipes (
    id integer primary key,
    nome text not null,
    estande text not null,
    nome_pendente boolean not null default false,
    bloqueado boolean not null default false
);

create table if not exists public.banca_temporizadores (
    equipe_id integer primary key references public.banca_equipes(id),
    estado text not null default 'idle' check (estado in ('idle','running','paused','finished')),
    iniciado_em timestamptz,
    segundos_decorridos integer not null default 0 check (segundos_decorridos>=0),
    duracao_segundos integer not null default 300 check (duracao_segundos>=0),
    versao integer not null default 0
);

create table if not exists public.banca_avaliacoes (
    id bigint generated by default as identity primary key,
    equipe_id integer not null references public.banca_equipes(id),
    usuario_id bigint not null references public.banca_usuarios(id),
    c1 integer not null check (c1 between 0 and 5),
    c2 integer not null check (c2 between 0 and 5),
    c3 integer not null check (c3 between 0 and 5),
    cameras_disponiveis integer not null check (cameras_disponiveis between 1 and 2),
    cameras_usadas integer not null check (cameras_usadas between 1 and 2),
    observacoes jsonb not null,
    notes text not null default '',
    updated_at timestamptz not null default now(),
    unique(equipe_id, usuario_id),
    check (cameras_usadas <= cameras_disponiveis)
);

create table if not exists public.banca_auditoria (
    id bigint generated by default as identity primary key,
    usuario_id bigint references public.banca_usuarios(id),
    equipe_id integer references public.banca_equipes(id),
    evento text not null,
    detalhe text not null default '',
    created_at timestamptz not null default now()
);

