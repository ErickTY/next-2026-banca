CREATE OR REPLACE FUNCTION public.banca_importar_manual(
 p_admin bigint,p_equipe integer,p_usuario bigint,
 p_c1 integer,p_c2 integer,p_c3 integer,p_disponiveis integer,p_usadas integer,
 p_obs jsonb,p_notas text,p_foto_path text,p_foto_sha256 text,
 p_substituir boolean DEFAULT false
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp
AS $$
DECLARE n jsonb;
BEGIN
 IF NOT EXISTS(SELECT 1 FROM public.banca_usuarios
               WHERE id=p_admin AND papel='admin' AND ativo) THEN
   RAISE EXCEPTION 'Somente coordenacao pode importar';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM public.banca_usuarios
               WHERE id=p_usuario AND papel='judge' AND ativo) THEN
   RAISE EXCEPTION 'Avaliador invalido ou inativo';
 END IF;
 IF length(p_foto_sha256)<>64 OR
    p_foto_path !~ '^2026/[0-9]+/[a-zA-Z0-9_-]+\.jpg$' THEN
   RAISE EXCEPTION 'Comprovante fotografico invalido';
 END IF;
 PERFORM 1 FROM public.banca_equipes WHERE id=p_equipe FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Equipe inexistente'; END IF;
 IF EXISTS(SELECT 1 FROM public.banca_importacoes
           WHERE equipe_id=p_equipe AND usuario_id=p_usuario
           AND foto_sha256=p_foto_sha256) THEN
    RAISE EXCEPTION 'Essa fotografia ja foi contabilizada';
 END IF;
 IF NOT p_substituir AND EXISTS(SELECT 1 FROM public.banca_avaliacoes
      WHERE equipe_id=p_equipe AND usuario_id=p_usuario) THEN
   RAISE EXCEPTION 'Avaliacao existente: confirme a substituicao';
 END IF;
 SELECT public.banca_salvar_avaliacao(
    p_equipe,p_usuario,p_c1,p_c2,p_c3,p_disponiveis,p_usadas,p_obs,p_notas) INTO n;
 INSERT INTO public.banca_importacoes(
   equipe_id,usuario_id,importado_por,foto_path,foto_sha256,total)
 VALUES(p_equipe,p_usuario,p_admin,p_foto_path,p_foto_sha256,p_c1+p_c2+p_c3);
 INSERT INTO public.banca_auditoria(usuario_id,equipe_id,evento,detalhe)
 VALUES(p_admin,p_equipe,'manual_photo_import',
  'avaliador='||p_usuario||'; total='||(p_c1+p_c2+p_c3)||
  '; hash='||left(p_foto_sha256,16)||'; substituiu='||p_substituir);
 RETURN jsonb_build_object('ok',true,'total',p_c1+p_c2+p_c3);
END;
$$;

CREATE OR REPLACE FUNCTION public.banca_limpar_avaliacoes(
 p_admin bigint,p_equipe integer DEFAULT NULL,p_confirmacao text DEFAULT ''
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp
AS $$
DECLARE n integer;
BEGIN
 IF p_confirmacao<>'APAGAR NOTAS' THEN
   RAISE EXCEPTION 'Confirmacao ausente';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM public.banca_usuarios
     WHERE id=p_admin AND papel='admin' AND ativo) THEN
   RAISE EXCEPTION 'Acesso negado';
 END IF;
 IF p_equipe IS NOT NULL AND NOT EXISTS(
     SELECT 1 FROM public.banca_equipes WHERE id=p_equipe) THEN
   RAISE EXCEPTION 'Equipe desconhecida';
 END IF;
 -- Exclui do ranking; mantem trilha de auditoria e fotos para rastreabilidade.
 IF p_equipe IS NULL THEN
   DELETE FROM public.banca_avaliacoes;
 ELSE
   DELETE FROM public.banca_avaliacoes WHERE equipe_id=p_equipe;
 END IF;
 GET DIAGNOSTICS n=ROW_COUNT;
 INSERT INTO public.banca_auditoria(usuario_id,equipe_id,evento,detalhe)
 VALUES(p_admin,p_equipe,'evaluation_history_cleared',
        'notas apagadas='||n||'; grupo='||coalesce(p_equipe::text,'TODOS'));
 RETURN jsonb_build_object('apagadas',n);
END;
$$;

