-- Uma transação por alteração de temporizador. Evita condições de corrida.
create or replace function public.banca_operar_tempo(
    p_equipe integer,
    p_acao text,
    p_usuario bigint,
    p_motivo text default ''
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
    t public.banca_temporizadores%rowtype;
    anterior text;
    instante timestamptz := clock_timestamp();
    decorrido integer;
begin
    if not exists(select 1 from public.banca_usuarios
                  where id=p_usuario and ativo=true and papel='admin') then
        raise exception 'Somente coordenação pode operar cronômetros';
    end if;
    select * into t from public.banca_temporizadores
    where equipe_id=p_equipe for update;
    if not found then
        raise exception 'Grupo não encontrado';
    end if;
    anterior := t.estado;
    decorrido := t.segundos_decorridos;
    if t.estado='running' and t.iniciado_em is not null then
        decorrido := decorrido + greatest(0, floor(extract(epoch from instante-t.iniciado_em))::integer);
    end if;
    if p_acao='start' and t.estado='idle' then
        t.estado := 'running';
        t.iniciado_em := instante;
        t.segundos_decorridos := 0;
    elsif p_acao='pause' and t.estado='running' then
        t.estado := 'paused';
        t.iniciado_em := null;
        t.segundos_decorridos := decorrido;
    elsif p_acao='resume' and t.estado='paused' then
        t.estado := 'running';
        t.iniciado_em := instante;
    elsif p_acao='finish' and t.estado in ('running','paused') then
        t.estado := 'finished';
        t.iniciado_em := null;
        t.segundos_decorridos := decorrido;
    elsif p_acao='reset' then
        if length(trim(coalesce(p_motivo,'')))<10 then
            raise exception 'Motivo obrigatório para zerar';
        end if;
        t.estado := 'idle';
        t.iniciado_em := null;
        t.segundos_decorridos := 0;
        t.duracao_segundos := 300;
    elsif p_acao='extend' and t.estado in ('running','paused','finished') then
        if length(trim(coalesce(p_motivo,'')))<10 then
            raise exception 'Motivo obrigatório para tempo adicional';
        end if;
        t.duracao_segundos := t.duracao_segundos + 60;
    else
        raise exception 'Ação incompatível com estado atual';
    end if;
    t.versao := t.versao + 1;
    update public.banca_temporizadores
        set estado=t.estado,iniciado_em=t.iniciado_em,
            segundos_decorridos=t.segundos_decorridos,
            duracao_segundos=t.duracao_segundos,versao=t.versao
        where equipe_id=p_equipe;
    insert into public.banca_auditoria(usuario_id,equipe_id,evento,detalhe)
    values(p_usuario,p_equipe,'timer_'||p_acao,
           anterior||'→'||t.estado||'; duração='||t.duracao_segundos||
           '; motivo='||left(coalesce(p_motivo,''),400));
    return jsonb_build_object('estado',t.estado,'duracao',t.duracao_segundos,'versao',t.versao);
end;
$$;

-- Avaliação e auditoria no MESMO commit, mesmo com múltiplos juízes simultâneos.
create or replace function public.banca_salvar_avaliacao(
    p_equipe integer,
    p_usuario bigint,
    p_c1 integer,
    p_c2 integer,
    p_c3 integer,
    p_disponiveis integer,
    p_usadas integer,
    p_obs jsonb,
    p_notas text
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp
as $$
declare
    _id bigint;
    _item text;
    _valor text;
    _falha boolean := false;
begin
    -- Impede editar durante bloqueio e serializa com outras alterações do grupo.
    perform 1 from public.banca_equipes
      where id=p_equipe and bloqueado=false for update;
    if not found then
        raise exception 'Grupo não encontrado ou avaliação bloqueada';
    end if;
    if not exists(select 1 from public.banca_usuarios
                  where id=p_usuario and ativo=true and papel in ('judge','admin')) then
        raise exception 'Avaliador não autorizado';
    end if;
    if p_c1 not between 0 and 5 or p_c2 not between 0 and 5 or p_c3 not between 0 and 5 then
        raise exception 'Notas devem estar entre 0 e 5';
    end if;
    if p_usadas not between 1 and 2 or p_disponiveis not between 1 and 2 or p_usadas > p_disponiveis then
        raise exception 'Câmeras inválidas';
    end if;
    if jsonb_typeof(p_obs) is distinct from 'object' then
        raise exception 'Observações inválidas';
    end if;
    foreach _item in array array['A1','A2','A3','D1','D2'] loop
        _valor := p_obs->>_item;
        if (_item like 'A%' and _valor not in ('correto','erro','nao_testado')) or
           (_item like 'D%' and _valor not in ('alerta','falso_aceite','sem_leitura')) or
           _valor is null then
            raise exception 'Observação inválida: %',_item;
        end if;
        if _valor in ('erro','nao_testado','falso_aceite','sem_leitura') then
            _falha := true;
        end if;
    end loop;
    insert into public.banca_avaliacoes(
        equipe_id,usuario_id,c1,c2,c3,cameras_disponiveis,cameras_usadas,
        observacoes,notes,updated_at
    ) values (
        p_equipe,p_usuario,p_c1,p_c2,p_c3,p_disponiveis,p_usadas,
        p_obs,left(coalesce(p_notas,''),3000),clock_timestamp()
    ) on conflict(equipe_id,usuario_id) do update
      set c1=excluded.c1,c2=excluded.c2,c3=excluded.c3,
          cameras_disponiveis=excluded.cameras_disponiveis,
          cameras_usadas=excluded.cameras_usadas,observacoes=excluded.observacoes,
          notes=excluded.notes,updated_at=excluded.updated_at
    returning id into _id;
    insert into public.banca_auditoria(usuario_id,equipe_id,evento,detalhe)
    values(p_usuario,p_equipe,'evaluation_saved',
           'c1='||p_c1||'; c2='||p_c2||'; c3='||p_c3||'; cameras='||p_usadas);
    return jsonb_build_object('id',_id,'total',p_c1+p_c2+p_c3);
end;
$$;

